-- ============================================================================
-- 251: Bukti potong (withholding slips) — fase 2
-- ============================================================================
-- One row per bukti potong, the unit that later becomes one <Bpu> in the
-- Coretax BPPU XML. Amounts are computed server-side by the rule engine
-- (lib/tax-withholding-rules.ts) and stored with their inputs so a row can be
-- audited and recomputed. The counterparty identity is snapshotted so an
-- exported slip keeps the identity that was reported even if the master
-- changes later. Writes go through service-role server actions only; reads
-- follow the same finance scope as the master tables.
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.tax_withholding_slips (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id UUID NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  entity_id BIGINT NOT NULL REFERENCES public.tax_withholding_entities(id) ON DELETE RESTRICT,
  counterparty_id BIGINT NOT NULL REFERENCES public.tax_counterparties(id) ON DELETE RESTRICT,
  counterparty_name TEXT NOT NULL,
  counterparty_identity_type TEXT NOT NULL
    CHECK (counterparty_identity_type IN ('npwp', 'nik', 'foreign_tin', 'unknown')),
  counterparty_identity_number TEXT NOT NULL,
  period_month SMALLINT NOT NULL CHECK (period_month BETWEEN 1 AND 12),
  period_year SMALLINT NOT NULL CHECK (period_year BETWEEN 2000 AND 2100),
  invoice_date DATE NOT NULL,
  invoice_number TEXT NOT NULL CHECK (length(btrim(invoice_number)) > 0),
  description TEXT,
  object_code TEXT NOT NULL REFERENCES public.tax_object_codes(code) ON UPDATE CASCADE,
  pph_article TEXT NOT NULL CHECK (pph_article IN ('pph22', 'pph23', 'pph4_2', 'pph15', 'pph26')),
  gross_input_mode TEXT NOT NULL DEFAULT 'dpp' CHECK (gross_input_mode IN ('dpp', 'total_incl_vat')),
  gross_input_amount NUMERIC(20, 6) NOT NULL CHECK (gross_input_amount > 0),
  gross_amount NUMERIC(20, 6) NOT NULL CHECK (gross_amount > 0),
  rate_percent NUMERIC(6, 3) NOT NULL CHECK (rate_percent >= 0),
  rate_source TEXT NOT NULL CHECK (rate_source IN ('object_code', 'facility', 'nik_double', 'override')),
  rate_override_reason TEXT,
  facility_code TEXT NOT NULL DEFAULT 'N/A'
    CHECK (facility_code IN ('N/A', 'TaxExAr22', 'TaxExAr23', 'TaxExIntDep', 'TaxExIntPhtb', 'DTP', 'PP23', 'ETC', 'SKD')),
  facility_document_number TEXT,
  withholding_amount NUMERIC(18, 0) NOT NULL CHECK (withholding_amount >= 0),
  vat_rate_percent NUMERIC(6, 3) NOT NULL DEFAULT 0 CHECK (vat_rate_percent >= 0),
  vat_amount NUMERIC(18, 0) NOT NULL DEFAULT 0 CHECK (vat_amount >= 0),
  additional_cost NUMERIC(18, 2) NOT NULL DEFAULT 0 CHECK (additional_cost >= 0),
  total_amount NUMERIC(20, 6) NOT NULL CHECK (total_amount >= 0),
  document_type TEXT NOT NULL DEFAULT 'CommercialInvoice'
    CHECK (document_type IN ('TaxInvoice', 'CommercialInvoice', 'Announchment', 'Contract', 'PaymentProof', 'DeedofEngangement', 'DeedofGeneralMeetingStakeholder', 'StatementLetter', 'BankAccountNumber')),
  document_date DATE NOT NULL,
  withholding_date DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'ready', 'exported', 'reported', 'paid')),
  coretax_slip_number TEXT,
  account_code TEXT,
  account_name TEXT,
  trello_url TEXT,
  notes TEXT,
  source TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('manual', 'import_rekapan')),
  workbook_withholding_amount NUMERIC(18, 0),
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (rate_source <> 'override' OR rate_override_reason IS NOT NULL),
  CHECK (withholding_date >= make_date(period_year, period_month, 1)),
  CHECK (status NOT IN ('reported', 'paid') OR coretax_slip_number IS NOT NULL)
);

-- Re-importing the same workbook must not duplicate a slip; two lines of one
-- invoice with different object codes or amounts remain distinct.
CREATE UNIQUE INDEX IF NOT EXISTS idx_tax_withholding_slips_import_identity
  ON public.tax_withholding_slips (
    workspace_id, entity_id, counterparty_id, object_code,
    lower(btrim(invoice_number)), invoice_date, gross_amount
  );
CREATE INDEX IF NOT EXISTS idx_tax_withholding_slips_period
  ON public.tax_withholding_slips (workspace_id, entity_id, period_year, period_month, status);
CREATE INDEX IF NOT EXISTS idx_tax_withholding_slips_counterparty
  ON public.tax_withholding_slips (workspace_id, counterparty_id);

ALTER TABLE public.tax_withholding_slips ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.tax_withholding_slips FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.tax_withholding_slips TO authenticated;
GRANT ALL ON TABLE public.tax_withholding_slips TO service_role;
REVOKE ALL ON SEQUENCE public.tax_withholding_slips_id_seq FROM PUBLIC, anon, authenticated;
GRANT ALL ON SEQUENCE public.tax_withholding_slips_id_seq TO service_role;

DROP POLICY IF EXISTS tax_withholding_slips_read ON public.tax_withholding_slips;
CREATE POLICY tax_withholding_slips_read ON public.tax_withholding_slips
  FOR SELECT TO authenticated
  USING (public.workspace_has_tax_access(workspace_id));

DROP TRIGGER IF EXISTS set_updated_at_tax_withholding_slips ON public.tax_withholding_slips;
CREATE TRIGGER set_updated_at_tax_withholding_slips
  BEFORE UPDATE ON public.tax_withholding_slips
  FOR EACH ROW EXECUTE FUNCTION public.set_workspace_updated_at();

COMMIT;
