-- ============================================================================
-- 254: Setoran PPh — ID Billing dan NTPN (fase 5)
-- ============================================================================
-- One kode billing pays the PPh of one pasal (KAP + KJS) for one masa, not one
-- bukti potong, so payments are rows of their own keyed by entity, masa and
-- KAP/KJS. A record starts with the kode billing (15 digits) and the amount it
-- was made for; recording the NTPN (16 characters) marks it paid and moves the
-- reported slips of that group to `paid` in the same transaction. Writes go
-- through service-role server actions only; reads follow the finance scope.
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.tax_payment_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id UUID NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  entity_id BIGINT NOT NULL REFERENCES public.tax_withholding_entities(id) ON DELETE RESTRICT,
  period_month SMALLINT NOT NULL CHECK (period_month BETWEEN 1 AND 12),
  period_year SMALLINT NOT NULL CHECK (period_year BETWEEN 2000 AND 2100),
  pph_article TEXT NOT NULL CHECK (pph_article IN ('pph22', 'pph23', 'pph4_2', 'pph15', 'pph26')),
  kap TEXT NOT NULL CHECK (kap ~ '^[0-9]{6}$'),
  kjs TEXT NOT NULL CHECK (kjs ~ '^[0-9]{3}$'),
  billing_id TEXT NOT NULL CHECK (billing_id ~ '^[0-9]{15}$'),
  billing_amount NUMERIC(18, 0) NOT NULL CHECK (billing_amount > 0),
  billing_created_at DATE NOT NULL DEFAULT CURRENT_DATE,
  billing_valid_until DATE,
  ntpn TEXT CHECK (ntpn IS NULL OR ntpn ~ '^[0-9A-Z]{16}$'),
  paid_at DATE,
  paid_amount NUMERIC(18, 0) CHECK (paid_amount IS NULL OR paid_amount > 0),
  notes TEXT,
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  paid_recorded_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((ntpn IS NULL) = (paid_at IS NULL)),
  CHECK ((ntpn IS NULL) = (paid_amount IS NULL)),
  CHECK (billing_valid_until IS NULL OR billing_valid_until >= billing_created_at),
  UNIQUE (workspace_id, entity_id, billing_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_tax_payment_records_ntpn
  ON public.tax_payment_records (workspace_id, entity_id, ntpn)
  WHERE ntpn IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_tax_payment_records_period
  ON public.tax_payment_records (workspace_id, entity_id, period_year, period_month);

DROP TRIGGER IF EXISTS set_updated_at_tax_payment_records ON public.tax_payment_records;
CREATE TRIGGER set_updated_at_tax_payment_records
  BEFORE UPDATE ON public.tax_payment_records
  FOR EACH ROW EXECUTE FUNCTION public.set_workspace_updated_at();

ALTER TABLE public.tax_payment_records ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.tax_payment_records FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.tax_payment_records TO authenticated;
GRANT ALL ON TABLE public.tax_payment_records TO service_role;
REVOKE ALL ON SEQUENCE public.tax_payment_records_id_seq FROM PUBLIC, anon, authenticated;
GRANT ALL ON SEQUENCE public.tax_payment_records_id_seq TO service_role;

DROP POLICY IF EXISTS tax_payment_records_read ON public.tax_payment_records;
CREATE POLICY tax_payment_records_read ON public.tax_payment_records
  FOR SELECT TO authenticated
  USING (public.workspace_has_tax_access(workspace_id));

-- Records the NTPN of a billing and marks the reported slips of its group
-- (entity, masa, pasal, KAP, KJS) paid, in one transaction. p_version is the
-- record's updated_at the caller saw. Returns the number of slips moved.
CREATE OR REPLACE FUNCTION public.tax_record_payment_ntpn(
  p_workspace_id UUID,
  p_record_id BIGINT,
  p_ntpn TEXT,
  p_paid_at DATE,
  p_paid_amount NUMERIC,
  p_version TIMESTAMPTZ,
  p_recorded_by UUID
)
RETURNS INT
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_record public.tax_payment_records%ROWTYPE;
  v_moved INT;
BEGIN
  IF p_ntpn IS NULL OR p_ntpn !~ '^[0-9A-Z]{16}$' THEN
    RAISE EXCEPTION 'NTPN harus 16 huruf besar/angka.' USING ERRCODE = '22023';
  END IF;
  IF p_paid_at IS NULL OR p_paid_amount IS NULL OR p_paid_amount <= 0 THEN
    RAISE EXCEPTION 'Tanggal dan jumlah setoran wajib diisi.' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_record FROM public.tax_payment_records
    WHERE id = p_record_id AND workspace_id = p_workspace_id
    FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Catatan setoran tidak ditemukan.' USING ERRCODE = 'P0002';
  END IF;
  IF v_record.ntpn IS NOT NULL THEN
    RAISE EXCEPTION 'NTPN sudah tercatat untuk ID Billing ini; hapus dulu untuk mengganti.' USING ERRCODE = 'P0003';
  END IF;
  IF v_record.updated_at <> p_version THEN
    RAISE EXCEPTION 'Catatan setoran berubah sejak dibaca; muat ulang.' USING ERRCODE = 'P0003';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.tax_payment_records
    WHERE workspace_id = p_workspace_id AND entity_id = v_record.entity_id AND ntpn = p_ntpn AND id <> p_record_id
  ) THEN
    RAISE EXCEPTION 'NTPN % sudah dipakai catatan setoran lain.', p_ntpn USING ERRCODE = 'P0004';
  END IF;

  UPDATE public.tax_payment_records
    SET ntpn = p_ntpn, paid_at = p_paid_at, paid_amount = p_paid_amount, paid_recorded_by = p_recorded_by
    WHERE id = p_record_id;

  UPDATE public.tax_withholding_slips s
    SET status = 'paid'
    FROM public.tax_object_codes c
    WHERE c.code = s.object_code
      AND s.workspace_id = p_workspace_id
      AND s.entity_id = v_record.entity_id
      AND s.period_year = v_record.period_year
      AND s.period_month = v_record.period_month
      AND s.pph_article = v_record.pph_article
      AND c.kap = v_record.kap
      AND c.kjs = v_record.kjs
      AND s.status = 'reported';
  GET DIAGNOSTICS v_moved = ROW_COUNT;
  RETURN v_moved;
END $$;

-- Removes a recorded NTPN (typo, wrong record). The group's paid slips return
-- to `reported` unless another record of the same group still holds an NTPN.
CREATE OR REPLACE FUNCTION public.tax_clear_payment_ntpn(
  p_workspace_id UUID,
  p_record_id BIGINT,
  p_version TIMESTAMPTZ
)
RETURNS INT
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_record public.tax_payment_records%ROWTYPE;
  v_moved INT := 0;
BEGIN
  SELECT * INTO v_record FROM public.tax_payment_records
    WHERE id = p_record_id AND workspace_id = p_workspace_id
    FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Catatan setoran tidak ditemukan.' USING ERRCODE = 'P0002';
  END IF;
  IF v_record.ntpn IS NULL THEN
    RAISE EXCEPTION 'Catatan setoran ini belum punya NTPN.' USING ERRCODE = 'P0003';
  END IF;
  IF v_record.updated_at <> p_version THEN
    RAISE EXCEPTION 'Catatan setoran berubah sejak dibaca; muat ulang.' USING ERRCODE = 'P0003';
  END IF;

  UPDATE public.tax_payment_records
    SET ntpn = NULL, paid_at = NULL, paid_amount = NULL, paid_recorded_by = NULL
    WHERE id = p_record_id;

  IF NOT EXISTS (
    SELECT 1 FROM public.tax_payment_records
    WHERE workspace_id = p_workspace_id AND entity_id = v_record.entity_id
      AND period_year = v_record.period_year AND period_month = v_record.period_month
      AND pph_article = v_record.pph_article AND kap = v_record.kap AND kjs = v_record.kjs
      AND ntpn IS NOT NULL AND id <> p_record_id
  ) THEN
    UPDATE public.tax_withholding_slips s
      SET status = 'reported'
      FROM public.tax_object_codes c
      WHERE c.code = s.object_code
        AND s.workspace_id = p_workspace_id
        AND s.entity_id = v_record.entity_id
        AND s.period_year = v_record.period_year
        AND s.period_month = v_record.period_month
        AND s.pph_article = v_record.pph_article
        AND c.kap = v_record.kap
        AND c.kjs = v_record.kjs
        AND s.status = 'paid';
    GET DIAGNOSTICS v_moved = ROW_COUNT;
  END IF;
  RETURN v_moved;
END $$;

REVOKE ALL ON FUNCTION public.tax_record_payment_ntpn(UUID, BIGINT, TEXT, DATE, NUMERIC, TIMESTAMPTZ, UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.tax_record_payment_ntpn(UUID, BIGINT, TEXT, DATE, NUMERIC, TIMESTAMPTZ, UUID) TO service_role;
REVOKE ALL ON FUNCTION public.tax_clear_payment_ntpn(UUID, BIGINT, TIMESTAMPTZ) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.tax_clear_payment_ntpn(UUID, BIGINT, TIMESTAMPTZ) TO service_role;

COMMIT;
