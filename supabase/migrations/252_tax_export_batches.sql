-- ============================================================================
-- 252: Batch export XML BPPU (fase 3)
-- ============================================================================
-- One batch is one BpuBulk XML file handed to Coretax. The XML text is stored
-- so a batch can be downloaded again and audited even if the generator or the
-- Coretax schema changes later. Batches are immutable: a slip that must change
-- after export is voided back to draft (keeping a pointer to the batch it left)
-- and joins the next batch.
--
-- tax_create_export_batch() moves slips to `exported` and creates the batch in
-- one transaction, taking the sequence number under an entity-level lock so two
-- concurrent exports of the same masa cannot share a sequence or a slip.
-- Writes go through service-role server actions only.
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.tax_export_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id UUID NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  entity_id BIGINT NOT NULL REFERENCES public.tax_withholding_entities(id) ON DELETE RESTRICT,
  period_month SMALLINT NOT NULL CHECK (period_month BETWEEN 1 AND 12),
  period_year SMALLINT NOT NULL CHECK (period_year BETWEEN 2000 AND 2100),
  sequence SMALLINT NOT NULL CHECK (sequence >= 1),
  file_name TEXT NOT NULL CHECK (length(btrim(file_name)) > 0),
  schema_version TEXT NOT NULL DEFAULT 'BpuBulk-v3',
  slip_count INT NOT NULL CHECK (slip_count > 0),
  total_gross NUMERIC(20, 6) NOT NULL CHECK (total_gross >= 0),
  total_withholding NUMERIC(18, 0) NOT NULL CHECK (total_withholding >= 0),
  xml_sha256 TEXT NOT NULL CHECK (xml_sha256 ~ '^[0-9a-f]{64}$'),
  xml_content TEXT NOT NULL CHECK (length(xml_content) > 0),
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (workspace_id, entity_id, period_year, period_month, sequence)
);

CREATE INDEX IF NOT EXISTS idx_tax_export_batches_period
  ON public.tax_export_batches (workspace_id, entity_id, period_year, period_month, sequence);

ALTER TABLE public.tax_export_batches ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.tax_export_batches FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.tax_export_batches TO authenticated;
GRANT ALL ON TABLE public.tax_export_batches TO service_role;
REVOKE ALL ON SEQUENCE public.tax_export_batches_id_seq FROM PUBLIC, anon, authenticated;
GRANT ALL ON SEQUENCE public.tax_export_batches_id_seq TO service_role;

DROP POLICY IF EXISTS tax_export_batches_read ON public.tax_export_batches;
CREATE POLICY tax_export_batches_read ON public.tax_export_batches
  FOR SELECT TO authenticated
  USING (public.workspace_has_tax_access(workspace_id));

-- Slips remember the batch they belong to, and the batch they were voided from.
ALTER TABLE public.tax_withholding_slips
  ADD COLUMN IF NOT EXISTS export_batch_id BIGINT REFERENCES public.tax_export_batches(id) ON DELETE RESTRICT,
  ADD COLUMN IF NOT EXISTS voided_from_batch_id BIGINT REFERENCES public.tax_export_batches(id) ON DELETE RESTRICT,
  ADD COLUMN IF NOT EXISTS void_reason TEXT;

CREATE INDEX IF NOT EXISTS idx_tax_withholding_slips_export_batch
  ON public.tax_withholding_slips (export_batch_id);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tax_withholding_slips_exported_has_batch') THEN
    ALTER TABLE public.tax_withholding_slips
      ADD CONSTRAINT tax_withholding_slips_exported_has_batch
      CHECK (status <> 'exported' OR export_batch_id IS NOT NULL);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tax_withholding_slips_batch_only_when_exported') THEN
    ALTER TABLE public.tax_withholding_slips
      ADD CONSTRAINT tax_withholding_slips_batch_only_when_exported
      CHECK (export_batch_id IS NULL OR status IN ('exported', 'reported', 'paid'));
  END IF;
END $$;

-- Atomically creates a batch for the given ready slips and marks them exported.
-- The caller builds the XML from the same slip rows beforehand; the function
-- re-checks that every slip is still `ready`, unassigned, and in the requested
-- entity/masa, so a slip changed between preview and export aborts the batch.
CREATE OR REPLACE FUNCTION public.tax_create_export_batch(
  p_workspace_id UUID,
  p_entity_id BIGINT,
  p_period_year INT,
  p_period_month INT,
  p_slip_ids BIGINT[],
  p_file_name_prefix TEXT,
  p_schema_version TEXT,
  p_xml_content TEXT,
  p_xml_sha256 TEXT,
  p_created_by UUID
)
RETURNS TABLE (batch_id BIGINT, sequence SMALLINT, file_name TEXT)
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_ids BIGINT[] := (SELECT array_agg(DISTINCT id) FROM unnest(p_slip_ids) AS id);
  v_count INT;
  v_gross NUMERIC(20, 6);
  v_withholding NUMERIC(18, 0);
  v_sequence SMALLINT;
  v_batch_id BIGINT;
  v_file_name TEXT;
BEGIN
  IF v_ids IS NULL OR cardinality(v_ids) = 0 THEN
    RAISE EXCEPTION 'Tidak ada bukti potong untuk di-export.' USING ERRCODE = '22023';
  END IF;
  IF p_period_month NOT BETWEEN 1 AND 12 OR p_period_year NOT BETWEEN 2000 AND 2100 THEN
    RAISE EXCEPTION 'Masa pajak tidak valid.' USING ERRCODE = '22023';
  END IF;

  -- Serialise exports per entity so the sequence number is unique and slips
  -- cannot be claimed by two batches.
  PERFORM 1 FROM public.tax_withholding_entities
    WHERE id = p_entity_id AND workspace_id = p_workspace_id AND is_active
    FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Pemotong tidak ditemukan atau nonaktif.' USING ERRCODE = 'P0002';
  END IF;

  SELECT count(*), coalesce(sum(s.gross_amount), 0), coalesce(sum(s.withholding_amount), 0)
    INTO v_count, v_gross, v_withholding
  FROM (
    SELECT gross_amount, withholding_amount
    FROM public.tax_withholding_slips
    WHERE id = ANY (v_ids)
      AND workspace_id = p_workspace_id
      AND entity_id = p_entity_id
      AND period_year = p_period_year
      AND period_month = p_period_month
      AND status = 'ready'
      AND export_batch_id IS NULL
    FOR UPDATE
  ) s;
  IF v_count <> cardinality(v_ids) THEN
    RAISE EXCEPTION 'Sebagian bukti potong sudah berubah atau bukan status siap (% dari % cocok); muat ulang pratinjau.', v_count, cardinality(v_ids)
      USING ERRCODE = 'P0003';
  END IF;

  SELECT coalesce(max(b.sequence), 0) + 1 INTO v_sequence
  FROM public.tax_export_batches b
  WHERE b.workspace_id = p_workspace_id AND b.entity_id = p_entity_id
    AND b.period_year = p_period_year AND b.period_month = p_period_month;
  v_file_name := p_file_name_prefix || lpad(v_sequence::text, 2, '0') || '.xml';

  INSERT INTO public.tax_export_batches (
    workspace_id, entity_id, period_month, period_year, sequence, file_name, schema_version,
    slip_count, total_gross, total_withholding, xml_sha256, xml_content, created_by
  ) VALUES (
    p_workspace_id, p_entity_id, p_period_month, p_period_year, v_sequence, v_file_name, p_schema_version,
    v_count, v_gross, v_withholding, p_xml_sha256, p_xml_content, p_created_by
  ) RETURNING id INTO v_batch_id;

  UPDATE public.tax_withholding_slips
    SET status = 'exported', export_batch_id = v_batch_id
    WHERE id = ANY (v_ids);

  RETURN QUERY SELECT v_batch_id, v_sequence, v_file_name;
END $$;

REVOKE ALL ON FUNCTION public.tax_create_export_batch(UUID, BIGINT, INT, INT, BIGINT[], TEXT, TEXT, TEXT, TEXT, UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.tax_create_export_batch(UUID, BIGINT, INT, INT, BIGINT[], TEXT, TEXT, TEXT, TEXT, UUID) TO service_role;

COMMIT;
